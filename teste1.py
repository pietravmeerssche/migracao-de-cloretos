from sklearn.model_selection import train_test_split
x_treino, x_teste, y_treino, y_teste = train_test_split(independente, dependente, test_size = 0.3, random_state = 0)

"""### **Validação Cruzada**"""

from sklearn.model_selection import KFold, cross_validate

# Configuração de folds
kfold = KFold(n_splits = 5, shuffle=True, random_state = 0)

# Criação do modelo
from xgboost import XGBRegressor
modelo = XGBRegressor(n_estimators=200, max_depth=2, learning_rate=0.05, objective = "reg:squarederror", random_state=0)

# Validação cruzada
resultado = cross_validate(modelo, x_treino, y_treino, cv = kfold, scoring='r2', return_train_score=True)

# Resultados e comparação
print("R² Treino (Média):", resultado['train_score'].mean())
print("R² Validação (Média):", resultado['test_score'].mean())

"""**Treinamento dados treino completo**"""

xgboost = XGBRegressor(n_estimators=200, max_depth=2, learning_rate=0.05, objective="reg:squarederror", random_state=0)
xgboost.fit(x_treino, y_treino)

xgboost.score(x_treino, y_treino)

"""**TESTE**"""

